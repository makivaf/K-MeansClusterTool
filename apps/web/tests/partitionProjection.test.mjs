import assert from "node:assert/strict";
import { build } from "esbuild";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const bundle = await build({ absWorkingDir: root, entryPoints: ["apps/web/src/components/charts/PartitionProjection.tsx"], bundle: true, write: false,
  platform: "node", format: "cjs", packages: "external", jsx: "automatic", loader: { ".css": "empty" } });
const module = { exports: {} };
vm.runInThisContext(`(function(require,module,exports){${bundle.outputFiles[0].text}\n})`)(createRequire(import.meta.url), module, module.exports);
const { PartitionProjection, projectionDomain, projectionTick } = module.exports;
// Synthetic presentation fixtures; no scientific coordinates are recomputed.
const points = [{ x: -2.123456789, y: 3.987654321, cluster: 0 }, { x: 5.234567891, y: -1.123456789, cluster: 2 }];
const centers = points.map(point => ({ ...point }));
const snapshot = JSON.stringify({ points, centers });
const props = { points, centers, label: "Standard K-Means" };
const tree = PartitionProjection(props);
const chart = tree.props.children[0].props.children.props.children;
const children = React.Children.toArray(chart.props.children);
const axis = key => children.find(node => node.props.dataKey === key);
assert.equal(axis("x").props.label.value, "PC1");
assert.equal(axis("y").props.label.value, "PC2");
assert.equal(projectionTick(points[0].x), "-2.12");
assert.equal(projectionTick(points[0].y), "3.99");
assert.ok(axis("x").props.domain[0] < points[0].x);
assert.ok(axis("x").props.domain[1] > points[1].x);
const paired = PartitionProjection({ ...props, label: "Enhanced K-Means", points: points.map(point => ({ ...point, cluster: 1 })) });
const pairedChart = paired.props.children[0].props.children.props.children;
for (const key of ["x", "y"]) assert.deepEqual(axis(key).props.domain, React.Children.toArray(pairedChart.props.children).find(node => node.props.dataKey === key).props.domain);
assert.deepEqual(chart.props.margin, pairedChart.props.margin);
const scatter = children.filter(node => node.props.data);
assert.deepEqual(scatter.flatMap(node => node.props.data).slice(0, points.length), points);
assert.equal(scatter.at(-1).props.data, centers);
assert.equal(scatter.at(-1).props.shape, "diamond");
assert.equal(scatter[0].props.fill, 'var(--research-primary)');
const html = renderToStaticMarkup(React.createElement(PartitionProjection, props));
assert.match(html, /Cluster 0/); assert.match(html, /Cluster 2/);
assert.doesNotMatch(html, /Cluster 1|impairment/);
assert.match(html, /Projected cluster means/);
assert.doesNotMatch(renderToStaticMarkup(React.createElement(PartitionProjection, { ...props, centers: [] })), /projection-legend-diamond/);
assert.deepEqual(projectionDomain([]), [-1, 1]);
assert.deepEqual(projectionDomain([0, 0]), [-1, 1]);
assert.ok(projectionDomain([3, 3])[0] < 3 && projectionDomain([3, 3])[1] > 3);
assert.equal(JSON.stringify({ points, centers }), snapshot);
console.log("PASS paired projection domains/margins, two-decimal ticks, axis titles, exact coordinates/assignments, colors, verified marker legend, and degenerate display bounds");
