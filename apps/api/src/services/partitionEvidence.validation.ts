import assert from "node:assert/strict";
import { derivePartitionEvidence, PartitionEvidenceSchema } from "../../../../packages/shared/src/partitionEvidence";
import { loadSopEvaluation } from "./sopEvaluationArtifact";
import { loadDefenseGeometry } from "./defenseGeometryArtifact";
import { loadStudyEvidence } from "./studyEvidenceArtifact";

const fixture = derivePartitionEvidence([[0,0,1,1], [9,9,4,4], [0,1,0,1], [8,2,8,2]]);
assert.equal(fixture.modalReferenceRun, 0);
assert.equal(fixture.uniqueFinalPartitions, 2);
assert.equal(fixture.maximumDifferingParticipants, 2);
assert.ok(Math.abs(fixture.meanPairwiseAri) < 1e-12);
fixture.modalPartitionAri.forEach((v, i) => assert.ok(Math.abs(v.adjustedRandIndex - (i < 2 ? 1 : -.5)) < 1e-12));
assert.equal(PartitionEvidenceSchema.safeParse({ ...fixture, modalPartitionFrequency: 4 }).success, false);
assert.throws(() => derivePartitionEvidence([[0,1], [0]]));
const evaluation = loadSopEvaluation()!;
const geometry = loadDefenseGeometry(evaluation)!;
const study = loadStudyEvidence(evaluation, geometry);
const e = study.initializationEvidence!;
assert.deepEqual(e.standard!.partitionFrequencies.map(p => p.frequency), [22,8]);
assert.deepEqual(e.pcaRandom!.partitionFrequencies.map(p => p.frequency), [21,7,2]);
assert.deepEqual(e.enhanced!.partitionFrequencies.map(p => p.frequency), [3]);
assert.equal(e.standard!.pairwiseComparisons, 435);
assert.equal(e.pcaRandom!.pairwiseComparisons, 435);
assert.equal(e.enhanced!.pairwiseComparisons, 3);
assert.equal(study.standardAriBySeed!.filter(p => p.adjustedRandIndex === 1).length, 22);
assert.equal(study.ariBySeed.filter(p => p.adjustedRandIndex === 1).length, 21);
assert.ok(Math.abs(e.standard!.meanPairwiseAri - .9966654488269048) < 1e-12);
assert.ok(Math.abs(e.pcaRandom!.meanPairwiseAri - .9976378643414584) < 1e-12);
assert.equal(e.enhanced!.minimumPairwiseAri, 1);
console.log("PASS label invariance, modal ties, pairwise/modal ARI, strict aggregate contract, frozen assignment hashes and 30/30/3 historical experiments");
